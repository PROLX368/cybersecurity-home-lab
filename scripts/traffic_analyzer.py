
#!/usr/bin/env python3

import argparse
import json
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

from scapy.all import rdpcap, IP, TCP, UDP, ICMP


def analyze_capture(file_path):
    packets = rdpcap(str(file_path))

    ip_counter = Counter()
    protocol_counter = Counter()
    destination_ports = defaultdict(set)
    syn_counter = Counter()
    alerts = []

    for packet in packets:
        if IP not in packet:
            continue

        source = packet[IP].src

        ip_counter[source] += 1

        if TCP in packet:
            protocol_counter["TCP"] += 1

            tcp = packet[TCP]
            destination_ports[source].add(int(tcp.dport))

            flags = int(tcp.flags)

            if flags & 0x02 and not flags & 0x10:
                syn_counter[source] += 1

        elif UDP in packet:
            protocol_counter["UDP"] += 1
            destination_ports[source].add(int(packet[UDP].dport))

        elif ICMP in packet:
            protocol_counter["ICMP"] += 1

        else:
            protocol_counter["OTHER"] += 1

    for ip, ports in destination_ports.items():
        if len(ports) >= 10:
            alerts.append({
                "type": "POSSIBLE_PORT_SCAN",
                "source_ip": ip,
                "unique_destination_ports": len(ports),
                "severity": "MEDIUM"
            })

        if syn_counter[ip] >= 20:
            alerts.append({
                "type": "HIGH_SYN_ACTIVITY",
                "source_ip": ip,
                "syn_packets": syn_counter[ip],
                "severity": "MEDIUM"
            })

    report = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "capture_file": str(file_path),
        "total_packets": len(packets),
        "source_ips": dict(ip_counter),
        "protocols": dict(protocol_counter),
        "destination_ports": {
            ip: sorted(ports)
            for ip, ports in destination_ports.items()
        },
        "alerts": alerts
    }

    return report


def main():
    parser = argparse.ArgumentParser(
        description="Network Traffic Analyzer v2"
    )

    parser.add_argument(
        "-f", "--file",
        required=True,
        help="PCAP or PCAPNG file"
    )

    args = parser.parse_args()

    capture = Path(args.file)

    if not capture.is_file():
        parser.error(f"Capture file not found: {capture}")

    print("\n[+] Analyzing network traffic...")

    report = analyze_capture(capture)

    reports_dir = Path("reports")
    reports_dir.mkdir(exist_ok=True)

    output_file = reports_dir / "analysis-results.json"
    alerts_file = reports_dir / "security-alerts.json"

    output_file.write_text(
        json.dumps(report, indent=4),
        encoding="utf-8"
    )

    alerts_file.write_text(
        json.dumps(report["alerts"], indent=4),
        encoding="utf-8"
    )

    print("\n========== ANALYSIS RESULTS ==========")
    print(f"Total packets: {report['total_packets']}")

    print("\nSource IPs:")
    for ip, count in report["source_ips"].items():
        print(f"  {ip}: {count} packets")

    print("\nProtocols:")
    for protocol, count in report["protocols"].items():
        print(f"  {protocol}: {count}")

    print("\nSecurity alerts:")
    if report["alerts"]:
        for alert in report["alerts"]:
            print(f"  [{alert['severity']}] {alert['type']}")
    else:
        print("  No alerts generated by current rules.")

    print("\nGenerated files:")
    print(f"  {output_file}")
    print(f"  {alerts_file}")


if __name__ == "__main__":
    main()

